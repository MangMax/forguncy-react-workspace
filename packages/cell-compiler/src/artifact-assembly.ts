/**
 * Turns a bundler report into a Cell artifact — the assembly half of the boundary.
 *
 * Decision source: GitHub Issue #6 — "Spec: generated ReactCellType artifact and
 * compiler boundary"
 * (https://github.com/Mang-X/forguncy-react-workspace/issues/6). The artifact audits
 * live in `artifact-audits.ts`, and the `compileCell` orchestration that calls this
 * assembly lives in `artifact.ts`.
 *
 * Split out of `artifact.ts` by #162, under the shape-stabilisation Spec #152.
 */

import { CELL_RUNTIME_BINDING_CONTRACT } from "@forguncy-react-workspace/core";
import type { CellEntryKind, DependencyDecision, FrontendLibraryReference } from "@forguncy-react-workspace/core";

import {
  artifactOriginOf,
  auditArtifactSource,
  auditCodeBudget,
  auditDependencyDecisions,
  auditEmittedAssets,
  auditExternalImports,
  auditInlinedPackages,
  auditInlinedResourceUrls,
} from "./artifact-audits.ts";
import type { BundledCellModule, CompileCellOutcome, CompileCellResult } from "./artifact.ts";
import { renderAutoHeightInjection } from "./auto-height.ts";
import { cellResourcesNeedStyleInstaller, renderCellStyleInstaller } from "./cell-resources.ts";
import { dedupeCellArtifactDiagnostics } from "./diagnostics.ts";
import { renderCellEntryWrapper } from "./entry.ts";
import { auditFrontendLibraries, collectFrontendLibraries } from "./frontend-libraries.ts";

/**
 * The first line of every artifact.
 *
 * Fixed text, no timestamp and no tool version: #6 permits a non-deterministic
 * banner only if it is documented, and documenting one that does not exist would
 * be worse than emitting none. It states #6's source-of-truth rule because the
 * banner is the one place a person reading designer-held code will see it.
 */
export const CELL_ARTIFACT_BANNER =
  "/* Generated by @forguncy-react-workspace/cell-compiler. Do not edit: repository source is authoritative, this is deployment output. */";

/**
 * The artifact a compile produced, with whatever per-package attribution the bundler reported.
 *
 * One constructor for both outcomes, so the compiled and rejected paths cannot hand back documents
 * that differ in anything but the diagnostics.
 */
function artifactOf(
  code: string,
  frontendLibraries: readonly FrontendLibraryReference[],
  module: BundledCellModule,
): CompileCellResult {
  return {
    code,
    frontendLibraries,
    ...(module.inlinedPackageSizes === undefined ? {} : { inlinedPackageSizes: module.inlinedPackageSizes }),
    ...(module.resources === undefined ? {} : { inlinedResources: module.resources }),
  };
}

// ---------------------------------------------------------------------------
// Assembly
// ---------------------------------------------------------------------------

export interface AssembleCellArtifactInput {
  /** The bundler's single-artifact report. */
  readonly module: BundledCellModule;
  readonly dependencies: readonly DependencyDecision[];
  readonly entryKind?: CellEntryKind;
  readonly codeBudgetCharacters?: number;
  /**
   * Whether this Cell compiles height-adaptive (#185, Epic #184).
   *
   * `true` injects the ReactCellAutoHeight patch into the artifact head; `false`
   * (the explicit `heightMode: "fixed"` opt-out) omits it, and the artifact is
   * byte-identical to what this compiler produced before the injection existed.
   * Absent is **not** the opt-out: it reads as `true`, because `core`'s registry
   * materializes the default for every normalized Cell — an assembler caller that
   * says nothing is a test or a probe, and the injection is the behaviour the Epic
   * makes standard rather than a knob each caller re-decides.
   */
  readonly heightAdaptive?: boolean;
}

/**
 * Turns a bundler report into a Cell artifact, or refuses it with diagnostics.
 *
 * Checks run in a fixed order so the diagnostic list is itself deterministic —
 * two runs over the same input cannot report the same problems in a different
 * order, which matters because the list ends up in CI logs that get diffed.
 */
export function assembleCellArtifact(input: AssembleCellArtifactInput): CompileCellOutcome {
  const { module, dependencies } = input;

  const decisionDiagnostics = auditDependencyDecisions(dependencies);
  const importDiagnostics = auditExternalImports(module.externalImports ?? [], dependencies);
  const inlinedDiagnostics = auditInlinedPackages(module.inlinedPackages ?? [], dependencies, module.inlinedSpecifiers);
  const assetDiagnostics = auditEmittedAssets(module.emittedAssets ?? []);
  const collection = collectFrontendLibraries(dependencies);

  const wrapper = renderCellEntryWrapper({
    ...(input.entryKind === undefined ? {} : { entryKind: input.entryKind }),
    // The wrapper may only publish live props when the binding that declares the variable is
    // in this artifact; the bundler's report is the only source that knows (#83).
    runtimeBinding: module.runtimeBindingGenerated === true,
  });

  const wrapperSource = wrapper.status === "emitted" ? wrapper.source : "";
  // The artifact-scope props variable, declared *outside* the bundle and *before* it (#83).
  //
  // This placement is the seam, and both halves are load-bearing:
  //
  // - **outside the bundle's IIFE**, because the binding module is inside it, the entry
  //   wrapper is beside it, and only a declaration at the artifact's own scope is visible to
  //   both. Declared inside the bundle, the wrapper could not assign to it; declared after
  //   it, the initial value would not be there when the module body installs the provider.
  // - **only when a binding was generated**, because a façade-free artifact must not carry a
  //   name nothing uses — and a wrapper that assigned to an undeclared variable would be a
  //   `ReferenceError` at the first render, in strict mode, which every IIFE bundle is.
  //
  // `var` rather than a block-scoped declaration because the wrapper *reassigns* it, and the
  // initial value is the evaluation's wrapper-local `props`, which is what keeps a
  // `render-call` or `top-level-element-variable` shape working at all.
  //
  // Nothing here is a page global: a `var` in the platform's `new Function` body is a
  // per-evaluation binding exactly as the provider slot is per copy.
  const livePropsDeclaration =
    module.runtimeBindingGenerated === true && wrapper.status === "emitted"
      ? `var ${CELL_RUNTIME_BINDING_CONTRACT.livePropsVariable} = props;\n`
      : "";
  // The style installer (#98) goes before the bundle, beside the live-props declaration and for
  // the same structural reason: the stylesheet modules are inside the bundle, and a `var` or
  // `function` declaration at the artifact's own scope is the only thing both sides can see.
  //
  // Emitted only when a style was actually inlined. A Cell with no CSS must not carry a page-level
  // registry it never reads, and the *decision* is the bundler's report rather than a search of
  // `code` for a marker — a fixture port that reports no resources therefore gets the plain
  // artifact, exactly as it gets no live-props declaration.
  const styleInstaller = cellResourcesNeedStyleInstaller(module.resources ?? []) ? renderCellStyleInstaller() : "";
  // The auto-height injection (#185) goes before the bundle too, but for a different reason than
  // the two declarations above: it is not a shared binding, it is *earlier execution*. The patch
  // is three timing-tolerant mechanisms (prototype wrap, repair pass, observer — see
  // `auto-height.ts`), and artifact evaluation precedes the platform's own instantiation of this
  // cell, so the primary path is served no matter where in the artifact the block sits. Before
  // the bundle is still the deliberate choice: the injection is environment wiring in the same
  // family as the host-provider install, a reviewer expects platform-shaping code ahead of the
  // Cell's own, and an evaluation-time throw inside the bundle cannot then leave the patch
  // unapplied — the failure ordering reads correctly in either direction.
  //
  // It is deliberately *not* a bundler interception: #82's binding reaches the artifact because
  // a façade import pulls the virtual module in, while this patch must exist even in a Cell that
  // never imports the façade — a façade-free artifact is still a ReactCellType cell with the
  // same hardcoded container. Emitted once, here, the block is single by construction within one
  // artifact; across artifacts and re-compiles the prototype guard carries idempotency.
  const heightAdaptive = input.heightAdaptive ?? true;
  const autoHeight = heightAdaptive ? renderAutoHeightInjection() : "";
  const code = `${CELL_ARTIFACT_BANNER}\n${livePropsDeclaration}${styleInstaller}${autoHeight}${module.code}\n${wrapperSource}\n`;

  // The origin arithmetic needs the prefix's real length, because the bundle no longer
  // starts at "banner + newline" once a declaration, an installer or the injection sits
  // between them — see `artifactOriginOf` for why the length travels rather than being
  // re-derived.
  const prefixLength = livePropsDeclaration.length + styleInstaller.length + autoHeight.length;
  const sourceDiagnostics = auditArtifactSource(code, artifactOriginOf(module.code, prefixLength));
  const budgetDiagnostics = auditCodeBudget(code, input.codeBudgetCharacters);
  const metadataDiagnostics = auditFrontendLibraries(collection.libraries);
  const resourceDiagnostics = auditInlinedResourceUrls(module.resources ?? []);

  const diagnostics = dedupeCellArtifactDiagnostics([
    // The bundler's own findings first: when one of them names the same
    // condition an audit below also reports (an unmapped extension decision is
    // visible both in the plan and in the output report), the build's more
    // specific explanation — which can say *why* the mapping is unusable — is
    // the one a reader keeps after deduplication.
    ...(module.diagnostics ?? []),
    ...decisionDiagnostics,
    ...importDiagnostics,
    ...inlinedDiagnostics,
    ...assetDiagnostics,
    ...resourceDiagnostics,
    ...collection.diagnostics,
    ...(wrapper.status === "emitted" ? [] : wrapper.diagnostics),
    ...sourceDiagnostics,
    ...budgetDiagnostics,
    ...metadataDiagnostics,
  ]);

  // A wrapper that could not be emitted always contributes a diagnostic, so the
  // second half of this test is redundant at runtime and present for the type
  // system: it is what narrows `wrapper` to the emitted case below.
  if (diagnostics.length > 0 || wrapper.status !== "emitted") {
    // The composed source travels with the rejection: the diagnostics are *about* this document, and
    // a caller recording a size verdict has to identify the artifact the verdict measured rather
    // than a re-derivation of it. A wrapper that could not be emitted leaves the code incomplete, so
    // it is not handed back — there is no artifact, only a diagnostic saying why.
    return {
      status: "rejected",
      diagnostics,
      ...(wrapper.status === "emitted"
        ? { artifact: artifactOf(code, collection.libraries, module) }
        : {}),
    };
  }

  return {
    status: "compiled",
    artifact: artifactOf(code, collection.libraries, module),
    entryKind: wrapper.kind,
  };
}
